#!/usr/bin/env python3
"""Write site/tokens.css from design/tokens.json.

Standard library only. The site never holds a raw colour, length or duration:
everything it uses comes from the custom properties written here.

Usage: scripts/tokens-to-css.py [tokens.json] [out.css]
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "design" / "tokens.json"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "site" / "tokens.css"


def colors(scheme):
    return [f"  --color-{name}: {value};" for name, value in scheme.items()]


def scale(prefix, table, unit="px"):
    return [f"  --{prefix}-{key}: {value}{unit};" for key, value in table.items()]


def main():
    t = json.loads(SRC.read_text(encoding="utf-8"))
    light, dark = t["color"]["light"], t["color"]["dark"]
    hexes = t["hex"]
    font = t["font"]
    motion = t["motion"]

    base = []
    base += scale("space", t["space"])
    base += scale("radius", t["radius"])
    base += scale("border", t["border-width"])
    base += scale("hex-size", hexes["size"])
    base.append(f"  --hex-gap: {hexes['gap']}px;")
    base.append(f'  --font-family: "{font["family"]}", system-ui, sans-serif;')
    base += scale("font-size", font["size"])
    base += scale("font-weight", font["weight"], unit="")
    base.append(f"  --motion-hive-open: {motion['hive-open']['duration-ms']}ms;")
    base.append(f"  --motion-hive-scale-from: {motion['hive-open']['scale-from']};")
    base.append(f"  --motion-hive-easing: {motion['hive-open']['easing']};")
    base.append(f"  --motion-hover: {motion['hover']['duration-ms']}ms;")

    out = [
        "/* Generated by scripts/tokens-to-css.py from design/tokens.json. Do not edit. */",
        "",
        ":root {",
        "  color-scheme: light dark;",
        *base,
        *colors(light),
        "}",
        "",
        "@media (prefers-color-scheme: dark) {",
        "  :root {",
        *["  " + line for line in colors(dark)],
        "  }",
        "}",
        "",
        "/* A section can pin a scheme whatever the system asks for. */",
        '[data-scheme="light"] {',
        "  color-scheme: light;",
        *colors(light),
        "}",
        "",
        '[data-scheme="dark"] {',
        "  color-scheme: dark;",
        *colors(dark),
        "}",
        "",
        "/* .inv sections invert the page: dark on a light page, light on a dark one. */",
        ".inv {",
        "  color-scheme: dark;",
        *colors(dark),
        "}",
        "",
        "@media (prefers-color-scheme: dark) {",
        "  .inv {",
        "    color-scheme: light;",
        *["  " + line for line in colors(light)],
        "  }",
        "}",
        "",
    ]
    if motion.get("respect-reduced-motion"):
        out += [
            "@media (prefers-reduced-motion: reduce) {",
            "  :root {",
            "    --motion-hive-open: 0ms;",
            "    --motion-hover: 0ms;",
            "  }",
            "}",
            "",
        ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT) if OUT.is_relative_to(ROOT) else OUT}")


if __name__ == "__main__":
    main()
