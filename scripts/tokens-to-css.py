#!/usr/bin/env python3
"""Write site/tokens.css from the `site` block of design/tokens.json.

Standard library only. The site is light only: there is no dark block and no
scheme switch. The site never holds a raw colour, length or duration: everything
it uses comes from the custom properties written here. The app keys of the
tokens file are not read.

Usage: scripts/tokens-to-css.py [tokens.json] [out.css]
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "design" / "tokens.json"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "site" / "tokens.css"


def scale(prefix, table, unit="px"):
    pre = f"{prefix}-" if prefix else ""
    return [f"  --{pre}{key}: {value}{unit};" for key, value in table.items() if not key.startswith("$")]


def main():
    s = json.loads(SRC.read_text(encoding="utf-8"))["site"]
    motion = s["motion"]
    durations = {k: v for k, v in motion.items() if k.startswith("duration")}

    lines = ["  color-scheme: light;"]
    lines += scale("color", s["color"], unit="")
    lines += scale("sbarah", s["sbarah"], unit="")
    lines += scale("radius", s["radius"])
    lines += scale("space", s["space"])
    lines += scale("border", s["border"])
    lines += scale("type", s["type"])
    lines += scale("target", s["target"])
    lines += scale("hex", s["hex"])
    lines.append(f'  --font-family: "{s["font"]["family"]}", system-ui, sans-serif;')
    lines += scale("font-weight", s["font"]["weight"], unit="")
    lines.append(f"  --ease-out: {motion['easing']};")
    lines += scale("", durations, unit="ms")
    lines += scale("scene", s["scene"], unit="")

    out = [
        "/* Generated by scripts/tokens-to-css.py from the site block of design/tokens.json. Do not edit. */",
        "",
        ":root {",
        *lines,
        "}",
        "",
        "/* Reduced motion zeroes every duration. */",
        "@media (prefers-reduced-motion: reduce) {",
        "  :root {",
        *[f"    --{k}: 0ms;" for k in durations],
        "  }",
        "}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT) if OUT.is_relative_to(ROOT) else OUT}")


if __name__ == "__main__":
    main()
